/** Build the portable plugin from repository source. Run with Bun. */
import { mkdir, readFile, writeFile, readdir, lstat, rm } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';
import { buildServer } from '../apps/mcp/src/tools.ts';
import { Client } from '../apps/mcp/node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js';
import { InMemoryTransport } from '../apps/mcp/node_modules/@modelcontextprotocol/sdk/dist/esm/inMemory.js';

const repo=resolve(import.meta.dir,'..');
const root=resolve(repo,'plugins/civpulse');
const parse=async file=>JSON.parse(await readFile(resolve(root,file),'utf8'));
const manifest=await parse('plugin.json');
const legacy=await parse('.codex-plugin/plugin.json');
const mcp=JSON.parse(await readFile(resolve(repo,'plugins/civpulse-mcp.json'),'utf8'));
const app=await parse('.app.json');
assert.equal(manifest.$schema,'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json');
assert.equal(mcp.$schema,'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json');
assert.equal(manifest.name,'civpulse');
assert.match(manifest.version,/^\d+\.\d+\.\d+$/);
for(const key of ['name','version','description','author']) assert.deepEqual(manifest[key],legacy[key]);
const ui=manifest.extensions['com.openai'].interface;
assert.deepEqual(ui,legacy.interface);
assert.ok(ui.shortDescription.length<=30);
assert.ok(Array.isArray(ui.capabilities));
assert.equal(ui.category,'Productivity');
assert.equal(legacy.skills,'./skills');
assert.equal(legacy.apps,'./.app.json');
assert.equal(manifest.extensions['com.openai'].apps,'./.app.json');
assert.equal(app.apps.civpulse.id,'asdk_app_6adb7102fd988191a89f556db8116075');
assert.equal(legacy.mcpServers,undefined);
assert.equal(await Bun.file(resolve(root,'mcp.json')).exists(),false);
assert.equal(await Bun.file(resolve(root,'.mcp.json')).exists(),false);
assert.equal(mcp.mcpServers.civpulse.url,'https://api.civpulse.org/functions/v1/mcp');
assert.equal(mcp.mcpServers.civpulse.type,'streamable-http');
assert.deepEqual(mcp.mcpServers.civpulse.extensions['com.openai'].auth.client,{mode:'dcr'});
for(const field of ['logo','composerIcon']){
  const path=resolve(root,ui[field]); assert.ok(path.startsWith(root+'/'));
  const svg=await readFile(path,'utf8'); assert.match(svg,/viewBox="0 0 64 64"/);
}
const references=[];
let skillCount = 0;
for(const name of await readdir(resolve(root,'skills'))){
  skillCount++;
  const text=await readFile(resolve(root,'skills',name,'SKILL.md'),'utf8');
  const front=Bun.YAML.parse(text.match(/^---\n([\s\S]*?)\n---\n/)[1]);
  assert.equal(front.name,name);assert.ok(typeof front.description==='string'&&front.description.trim());
  const agent=Bun.YAML.parse(await readFile(resolve(root,'skills',name,'agents/openai.yaml'),'utf8'));
  assert.equal(typeof agent.policy.allow_implicit_invocation,'boolean');
  for(const key of ['display_name','short_description']) assert.ok(agent.interface[key]?.trim());
  for(const [,link] of text.matchAll(/\]\(([^)]+)\)/g)){
    if(/^https?:/.test(link)) continue;
    const path=resolve(root,'skills',name,link);assert.ok(path.startsWith(root+'/'));references.push(path);
  }
}

// Tool discovery needs no credentials or database calls; reuse the actual server schemas.
const server=buildServer({}, {id:'00000000-0000-4000-8000-000000000000'});
const client=new Client({name:'civpulse-plugin-builder',version:manifest.version});
const [a,b]=InMemoryTransport.createLinkedPair();
let tools;
try { await server.connect(a);await client.connect(b);tools=(await client.listTools()).tools; }
finally { await client.close();await server.close(); }
assert.ok(tools.length>0&&tools.length<128);
assert.equal(new Set(tools.map(t=>t.name)).size,tools.length);
assert.ok(tools.every(t=>typeof t.annotations?.readOnlyHint==='boolean'));
const guide=`# Civic Pulse MCP tools\n\nGenerated by \`bun run plugin:build\` from the server’s actual tool schemas.\nThere are ${tools.length} tools. Consult live tool schemas for parameter types and defaults.\n\nAll MCP access requires OAuth. Reads follow the connected account’s visibility.\nAccount search, promotion, content and image writes require an administrator. The only non-admin write is\n\`update_my_profile\`, which updates the caller’s display name. Use search_users and promote_user_to_admin for explicitly requested account administration.\nAuth account provisioning/deletion, demotion, password resets, RLS changes and website deployment are outside this plugin.\n\n| Tool | Access | Purpose |\n| --- | --- | --- |\n${tools.map(t=>`| \`${t.name}\` | ${t.name==='search_users'?'Admin read':t.annotations.readOnlyHint?'Read':t.name==='update_my_profile'?'Own profile':'Admin write'} | ${t.description.replaceAll('|','\\|').replaceAll('\n',' ')} |`).join('\n')}\n`;
await writeFile(resolve(root,'references/tools.md'),guide);
await writeFile(resolve(root,'references/tool-schemas.json'),JSON.stringify(tools,null,2)+'\n');
for(const path of references) await lstat(path);

const files=[];
async function walk(folder){for(const entry of await readdir(folder,{withFileTypes:true})){
  const path=resolve(folder,entry.name);const stat=await lstat(path);
  assert.ok(!stat.isSymbolicLink(),`Symlink: ${path}`);
  assert.ok(!['node_modules','.git','.env','.dev.vars','marketplace.json'].includes(entry.name),`Excluded file: ${path}`);
  if(entry.isDirectory()) await walk(path);else {assert.ok(stat.size<5*1024*1024);files.push(path.slice(dirname(root).length+1));}
}}
await walk(root);files.sort();
const archive=resolve(repo,`dist/plugins/civpulse-${manifest.version}.zip`);
await mkdir(dirname(archive),{recursive:true});await rm(archive,{force:true});
const zip=Bun.spawn(['zip','-X','-q',archive,...files],{cwd:dirname(root),stdout:'inherit',stderr:'inherit'});
assert.equal(await zip.exited,0);
const listing=Bun.spawn(['unzip','-Z1',archive],{stdout:'pipe',stderr:'inherit'});
const archived=(await new Response(listing.stdout).text()).trim().split('\n').sort();
assert.equal(await listing.exited,0);assert.deepEqual(archived,files);
const inspect=Bun.spawn(['unzip','-t',archive],{stdout:'pipe',stderr:'inherit'});
await new Response(inspect.stdout).text();assert.equal(await inspect.exited,0);
console.log(`Validated ${tools.length} tools, ${skillCount} skills and ${files.length} files.\n${archive}`);
