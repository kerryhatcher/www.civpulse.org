/** Generate the reviewed data migration; never fetch or guess civic data here. */
import { readFileSync, writeFileSync } from 'node:fs';
import { parseServiceDate } from '../apps/web/src/lib/offices';
const source = 'docs/research/2026-candidate-office-history.json';
const target = 'supabase/migrations/20261114010000_candidate_office_history.sql';
const data = JSON.parse(readFileSync(source, 'utf8'));
const quote = (s: string | null) => s === null ? 'null' : `'${s.replaceAll("'", "''")}'`;
const seen = new Set<string>();
const rows = data.records.map((r: Record<string, string | null>) => {
  const start = parseServiceDate(r.starts_on!, 'start')!;
  const end = parseServiceDate(r.ends_on ?? '', 'end');
  if (end && end.date < start.date) throw Error(`Reversed dates: ${r.person_slug}`);
  if (!/^https:\/\//.test(r.source_url!)) throw Error(`Missing official source: ${r.person_slug}`);
  const key = [r.person_slug, r.organization_slug, r.office_name, r.district, r.seat, start.date].join('|');
  if (seen.has(key)) throw Error(`Duplicate term: ${key}`);
  seen.add(key);
  return [r.person_slug,r.organization_slug,r.organization_name,r.office_name,r.district,r.seat,start.date,end?.date??null,start.precision,end?.precision??'day',r.selection_method,r.source_url].map(quote).join(', ');
});
const sql = `-- Generated by bun scripts/generate-office-history-migration.ts
-- Research, supporting official sources, date inferences and unresolved gaps:
-- ${source}
-- Existing people only. Reuse organizations by slug or exact normalized name;
-- retain all existing content. Missing profiles on a fresh database are skipped.
do $$
declare record_row record; person_uuid uuid; organization_uuid uuid; office_uuid uuid;
begin
  for record_row in select * from (values
${rows.map((r: string) => `    (${r})`).join(',\n')}
  ) as history(person_slug,organization_slug,organization_name,office_name,district,seat,starts_on,ends_on,starts_on_precision,ends_on_precision,selection_method,source_url) loop
    select id into person_uuid from public.people where slug = record_row.person_slug;
    if person_uuid is null then continue; end if;
    select id into organization_uuid from public.organizations
      where slug = record_row.organization_slug or lower(btrim(name)) = lower(btrim(record_row.organization_name))
      order by (slug = record_row.organization_slug) desc, created_at, id limit 1;
    if organization_uuid is null then
      insert into public.organizations(slug,name,description,website_url)
        values (record_row.organization_slug,record_row.organization_name,
          'Public office or governing body. Service histories are documented by the official sources linked from each officeholder record.',
          record_row.source_url) returning id into organization_uuid;
    end if;
    insert into public.offices(organization_id,name,district,seat)
      values (organization_uuid,record_row.office_name,record_row.district,record_row.seat)
      on conflict (organization_id,name,district,seat) do nothing;
    select id into office_uuid from public.offices where organization_id = organization_uuid
      and name = record_row.office_name and district = record_row.district and seat = record_row.seat;
    insert into public.office_terms(office_id,person_id,selection_method,starts_on,ends_on,source_url,starts_on_precision,ends_on_precision)
      values (office_uuid,person_uuid,record_row.selection_method,record_row.starts_on::date,record_row.ends_on::date,record_row.source_url,record_row.starts_on_precision,record_row.ends_on_precision)
      on conflict (office_id,person_id,starts_on) do nothing;
  end loop;
end;
$$;
`;
writeFileSync(target, sql);
console.log(`Generated ${rows.length} reviewed service records in ${target}`);
