// Bundle repository-owned source; Deno resolves the pinned runtime dependencies.
import { mkdir } from 'node:fs/promises';
const result = await Bun.build({
  entrypoints: ['apps/mcp/src/index.ts'], target: 'browser', format: 'esm',
  external: ['@modelcontextprotocol/server', '@supabase/supabase-js', 'zod'],
});
if (!result.success) throw new AggregateError(result.logs, 'MCP bundle failed');
await mkdir('supabase/functions/mcp', { recursive: true });
const path = 'supabase/functions/mcp/handler.js';
const source = '// Generated by bun run mcp:build; edit apps/mcp/src instead.\n' + await result.outputs[0].text();
if (process.argv.includes('--check')) {
  if (await Bun.file(path).text() !== source) throw new Error('MCP bundle is stale; run bun run mcp:build');
} else await Bun.write(path, source);
console.log('Built Supabase MCP function handler');
