#!/usr/bin/env bun
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const install = spawnSync('bun', ['install', '--frozen-lockfile'], { cwd: root, stdio: 'inherit' });
if (install.status !== 0) process.exit(install.status ?? 1);

// The common Git directory belongs to the original checkout, even in a worktree.
const git = spawnSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], {
  cwd: root, encoding: 'utf8',
});
if (git.status !== 0) throw new Error('Could not locate the shared checkout.');
const backendRoot = dirname(git.stdout.trim());
const status = spawnSync(resolve(root, 'node_modules/.bin/supabase'), ['status', '-o', 'env'], {
  cwd: backendRoot, encoding: 'utf8',
});
if (status.status !== 0) {
  console.error(status.stderr);
  console.error(`Start the shared backend with \`bun run db:start\` in ${backendRoot}, then rerun \`bun run worktree:setup\`.`);
  process.exit(1);
}
const settings = Object.fromEntries(status.stdout.split('\n').filter(line => line.includes('=')).map(line => {
  const index = line.indexOf('=');
  return [line.slice(0, index).trim(), line.slice(index + 1).trim().replace(/^"|"$/g, '')];
}));
if (!settings.API_URL || !settings.ANON_KEY) throw new Error('Supabase status did not return API_URL and ANON_KEY.');
const url = new URL(settings.API_URL);
if (!['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname)) {
  throw new Error('Worktree setup requires a local Supabase backend.');
}
// Never write the service-role key or other CLI status values into the web app.
writeFileSync(resolve(root, 'apps/web/.env.local'),
  `# Generated by bun run worktree:setup; shared local backend.\nPUBLIC_SUPABASE_URL=${JSON.stringify(settings.API_URL)}\nPUBLIC_SUPABASE_ANON_KEY=${JSON.stringify(settings.ANON_KEY)}\n`,
  { mode: 0o600 });
console.log(`Worktree ready. Shared Supabase: ${settings.API_URL}. Start Astro with bun run dev:worktree.`);
